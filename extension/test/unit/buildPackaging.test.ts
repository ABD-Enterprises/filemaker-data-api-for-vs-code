import { execFileSync } from 'child_process';
import { readFileSync } from 'fs';
import path from 'path';
import { pathToFileURL } from 'url';

import { describe, expect, it } from 'vitest';

const extensionDir = path.resolve(__dirname, '../..');
const script = (name: string): string => pathToFileURL(path.join(extensionDir, 'scripts', name)).href;

interface BundleOptions {
  minify?: boolean;
  sourcemap?: string | boolean;
  define?: Record<string, string>;
  external?: string[];
}

describe('production bundles', () => {
  it('minify, keep the source map out of the bundle, and define NODE_ENV', async () => {
    const config = (await import(/* @vite-ignore */ script('esbuild-config.mjs'))) as {
      extensionBundles: Record<string, BundleOptions>;
    };
    for (const options of Object.values(config.extensionBundles)) {
      expect(options.minify).toBe(true);
      expect(options.sourcemap).toBe('external');
      expect(options.define?.['process.env.NODE_ENV']).toBe('"production"');
      expect(options.external).toEqual(['vscode']);
    }
  });

  it('builds the Layout Mode UI minified, for production, without source maps', () => {
    const designer = JSON.parse(readFileSync(path.join(extensionDir, '../designer-ui/package.json'), 'utf8')) as {
      scripts: Record<string, string>;
    };
    expect(designer.scripts.build).toContain('--minify');
    expect(designer.scripts.build).toContain('NODE_ENV');
    expect(designer.scripts.build).toContain('production');
    expect(designer.scripts.build).not.toContain('--sourcemap');
  });

  it('keeps source maps and dev-only files out of the VSIX', () => {
    const ignore = readFileSync(path.join(extensionDir, '.vscodeignore'), 'utf8').split(/\r?\n/);
    for (const pattern of ['dist/**/*.map', 'eslint.config.mjs', 'scripts/**', 'docs/QA/**']) {
      expect(ignore, pattern).toContain(pattern);
    }
    expect(ignore).not.toContain('THIRD_PARTY_NOTICES.txt');
  });
});

describe('THIRD_PARTY_NOTICES.txt', () => {
  it('has a licence notice for every package bundled into the extension', async () => {
    const generator = (await import(/* @vite-ignore */ script('generate-third-party-notices.mjs'))) as {
      collectBundledPackages(): Promise<{ packages: Array<{ name: string; text: string }>; missing: string[] }>;
      renderNotices(packages: unknown[]): string;
    };
    const { packages, missing } = await generator.collectBundledPackages();

    // Fails, naming the package, when a bundled dependency ships no licence text.
    expect(missing).toEqual([]);
    const names = packages.map((pkg) => pkg.name);
    expect(names).toEqual(expect.arrayContaining(['axios', 'zod']));
    expect(packages.every((pkg) => pkg.text.length > 40)).toBe(true);

    // The committed file lists exactly the packages that are bundled (and is regenerated by
    // `npm run notices` when a dependency changes).
    const committed = readFileSync(path.join(extensionDir, 'THIRD_PARTY_NOTICES.txt'), 'utf8');
    expect(committed.replace(/\r\n/g, '\n')).toBe(generator.renderNotices(packages));
  }, 60_000);

  it('the check script passes on the committed file', () => {
    // --check exits 1 when the file is stale or a bundled package has no licence.
    expect(() =>
      execFileSync(process.execPath, [path.join(extensionDir, 'scripts/generate-third-party-notices.mjs'), '--check'], {
        cwd: extensionDir,
        stdio: 'pipe'
      })
    ).not.toThrow();
  }, 60_000);
});
