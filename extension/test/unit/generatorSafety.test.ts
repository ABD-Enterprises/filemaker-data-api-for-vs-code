import { mkdtemp, mkdir, readFile, rm, writeFile } from 'fs/promises';
import { tmpdir } from 'os';
import { join } from 'path';
import { afterEach, describe, expect, it, vi } from 'vitest';
import * as vscode from 'vscode';
import { TypeGenService } from '../../src/services/typeGenService';

const profile = { id: 'p', name: 'Dev', database: 'DB' } as never;
const roots: string[] = [];
const logger = { debug: vi.fn(), warn: vi.fn(), info: vi.fn(), error: vi.fn() };
async function fixture() {
  const root = await mkdtemp(join(tmpdir(), 'fm-generator-safety-')); roots.push(root);
  const service = new TypeGenService({ getLayoutSchema: async () => ({ supported: true, fields: [{ name: ' Name ', type: 'text' }] }) } as never,
    { listLayouts: async () => [' Contacts '] } as never, logger, { getWorkspaceRoot: () => root });
  return { root, service };
}
afterEach(async () => { for (const root of roots.splice(0)) await rm(root, { recursive: true, force: true }); vi.clearAllMocks(); });

describe('safe generated files', () => {
  it('never silently replaces unrelated client files, names every conflict, and cancels the whole write', async () => {
    const { root, service } = await fixture();
    for (const name of ['README.md', 'client.ts']) await writeFile(join(root, name), `user ${name}`);
    vi.mocked(vscode.window.showWarningMessage).mockResolvedValue('Cancel' as never);
    await expect(service.generateTypeScriptClient(profile, [' Contacts '], root)).rejects.toThrow(/cancelled/i);
    for (const name of ['README.md', 'client.ts']) expect(await readFile(join(root, name), 'utf8')).toBe(`user ${name}`);
    expect(vscode.window.showWarningMessage).toHaveBeenCalledWith(expect.stringMatching(/README.md[\s\S]*client.ts|client.ts[\s\S]*README.md/), { modal: true }, 'Overwrite', 'Skip existing', 'Cancel');
    await expect(readFile(join(root, 'types.ts'))).rejects.toMatchObject({ code: 'ENOENT' });
  });
  it('Skip existing preserves unrelated files while creating the other marked outputs', async () => {
    const { root, service } = await fixture();
    await writeFile(join(root, 'client.ts'), 'user code');
    vi.mocked(vscode.window.showWarningMessage).mockResolvedValue('Skip existing' as never);
    const result = await service.generateTypeScriptClient(profile, [' Contacts '], root);
    expect(await readFile(result.clientPath, 'utf8')).toBe('user code');
    expect(await readFile(result.readmePath, 'utf8')).toMatch(/^<!-- Generated by FileMaker Data API Tools/);
    expect(await readFile(result.typesPath, 'utf8')).toContain('Generated by FileMaker Data API Tools');
  });
  it('requires consent before replacing layout types and snippets, but refreshes its marked output', async () => {
    const { root, service } = await fixture();
    const artifact = await service.generateTypesForLayout(profile, ' Contacts ');
    await writeFile(artifact.filePath, 'unrelated types');
    vi.mocked(vscode.window.showWarningMessage).mockResolvedValue('Overwrite' as never);
    await service.generateTypesForAllLayouts(profile);
    expect(vscode.window.showWarningMessage).toHaveBeenCalledTimes(1);
    const snippetsDir = join(root, 'snippets'); await mkdir(snippetsDir, { recursive: true });
    const target = join(snippetsDir, 'filemaker-data-api.code-snippets');
    await writeFile(target, '{"mine":{"prefix":"mine","body":["keep"]}}');
    vi.mocked(vscode.window.showWarningMessage).mockResolvedValue('Skip existing' as never);
    await expect(service.generateSnippetsForLayout(profile, ' Contacts ')).rejects.toThrow(/Skipped existing/);
    expect(await readFile(target, 'utf8')).toBe('{"mine":{"prefix":"mine","body":["keep"]}}');
    expect(vscode.window.showWarningMessage).toHaveBeenCalledTimes(2);
    await service.generateTypesForLayout(profile, ' Contacts ');
    expect(vscode.window.showWarningMessage).toHaveBeenCalledTimes(2);
  });
  it('refuses output directories that are a file name such as README.md', async () => {
    const { root, service } = await fixture();
    await expect(service.generateTypeScriptClient(profile, [' Contacts '], join(root, 'README.md'))).rejects.toThrow(/folder|file name/i);
  });
});
