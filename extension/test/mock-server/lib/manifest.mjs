// Writes dataset-manifest.json and DATASET.md next to the seed.
//   node test/mock-server/lib/manifest.mjs           regenerate
//   node test/mock-server/lib/manifest.mjs --check   exit 1 when the committed files are stale
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { buildDataset } from './dataset.mjs';

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export function renderManifest() {
  const { manifest } = buildDataset();
  const json = `${JSON.stringify(manifest, null, 2)}\n`;
  const lines = [
    '# Mock dataset manifest',
    '',
    'Generated by `node test/mock-server/lib/manifest.mjs` from `lib/dataset.mjs` (seed ' +
      manifest.seed +
      '). Do not edit by hand;',
    '`dataset-manifest.json` has the full id lists. A unit test fails when these files are stale.',
    '',
    `Record totals: ${Object.entries(manifest.totals)
      .map(([k, v]) => `${k} ${v}`)
      .join(', ')}.`,
    '',
    "Values may contain `{{BASE}}`, `{{HOST}}` and `{{TOKEN}}`; the server replaces them per request with its own origin, host and the caller's session token.",
    ''
  ];
  for (const [db, info] of Object.entries(manifest.databases)) {
    lines.push(`## ${db}`, '');
    for (const [table, t] of Object.entries(info.tables)) {
      lines.push(`### ${db} / ${table} (${t.recordCount} records)`, '');
      const entries = Object.entries(t.conditions).filter(([k]) => k !== 'non-contiguous-ids');
      if (entries.length) {
        lines.push('| Condition | Count | Example record ids | What it is |', '|---|---|---|---|');
        for (const [id, ids] of entries.sort())
          lines.push(
            `| \`${id}\` | ${ids.length} | ${ids.slice(0, 6).join(', ')}${ids.length > 6 ? ', ...' : ''} | ${manifest.conditions[id] ?? ''} |`
          );
        lines.push('');
      }
      if (t.deletedIdGaps.length)
        lines.push(
          `Deleted-id gaps (record ids that do not exist): ${t.deletedIdGaps.slice(0, 12).join(', ')}${t.deletedIdGaps.length > 12 ? ', ...' : ''}.`,
          ''
        );
    }
  }
  lines.push(
    '## Hostile layout names (Quality)',
    '',
    manifest.hostileLayoutNames.map((n) => `- \`${JSON.stringify(n)}\``).join('\n'),
    ''
  );
  lines.push(
    '## Hostile field names (Quality / Hostile layout)',
    '',
    manifest.hostileFieldNames.map((n) => `- \`${JSON.stringify(n)}\``).join('\n'),
    ''
  );
  return { json, md: `${lines.join('\n')}\n` };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === fs.realpathSync(process.argv[1])) {
  const { json, md } = renderManifest();
  const files = { 'dataset-manifest.json': json, 'DATASET.md': md };
  if (process.argv.includes('--check')) {
    const stale = Object.entries(files).filter(
      ([n, c]) =>
        !fs.existsSync(path.join(dir, n)) || fs.readFileSync(path.join(dir, n), 'utf8').replace(/\r\n/g, '\n') !== c
    );
    if (stale.length) {
      console.error(
        `Stale: ${stale.map(([n]) => n).join(', ')}. Run: node test/mock-server/lib/manifest.mjs`
      );
      process.exit(1);
    }
    console.log('manifest is up to date');
  } else {
    for (const [n, c] of Object.entries(files)) fs.writeFileSync(path.join(dir, n), c);
    console.log('wrote', Object.keys(files).join(', '));
  }
}
