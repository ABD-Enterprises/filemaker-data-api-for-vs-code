import { lstat, mkdir, readFile, writeFile } from 'fs/promises';
import { dirname } from 'path';
import * as vscode from 'vscode';

export const GENERATED_MARKER = 'Generated by FileMaker Data API Tools.';

export class GenerationCancelledError extends Error {
  public constructor() { super('Generation cancelled.'); }
}

/** Only a header owned by this extension permits an unattended refresh. */
export function isGeneratedFile(text: string): boolean {
  return text.startsWith(`/**\n * ${GENERATED_MARKER}\n`) ||
    text.startsWith(`// ${GENERATED_MARKER}\n`) ||
    text.startsWith(`<!-- ${GENERATED_MARKER} -->\n`) ||
    text.startsWith(`{\n  "$comment": "${GENERATED_MARKER}",\n`);
}

/** Review all collisions before writing any file. A dismissed dialog means Cancel. */
export async function writeGeneratedFiles(files: Array<{ path: string; content: string }>): Promise<string[]> {
  const existing = new Map<string, string>();
  const conflicts: string[] = [];
  for (const file of files) {
    try {
      const info = await lstat(file.path);
      if (!info.isFile() || info.isSymbolicLink()) throw new Error(`Cannot replace ${file.path}: it is not a regular file.`);
      const text = await readFile(file.path, 'utf8');
      existing.set(file.path, text);
      if (!isGeneratedFile(text)) conflicts.push(file.path);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
    }
  }
  let choice: string | undefined = 'Overwrite';
  if (conflicts.length) {
    choice = await vscode.window.showWarningMessage(
      `These files contain content that was not generated by FileMaker Data API Tools:\n${conflicts.join('\n')}\nChoose what to do with the existing files.`,
      { modal: true }, 'Overwrite', 'Skip existing', 'Cancel'
    );
    if (choice !== 'Overwrite' && choice !== 'Skip existing') throw new GenerationCancelledError();
  }
  const skipped = choice === 'Skip existing' ? conflicts : [];
  for (const file of files) {
    if (skipped.includes(file.path)) continue;
    await mkdir(dirname(file.path), { recursive: true });
    // Do not replace a file that appeared or changed while the confirmation was open.
    if (existing.has(file.path)) {
      const info = await lstat(file.path);
      if (info.isSymbolicLink() || await readFile(file.path, 'utf8') !== existing.get(file.path)) {
        throw new Error(`${file.path} changed during generation. Run the command again.`);
      }
      await writeFile(file.path, file.content, 'utf8');
    } else {
      await writeFile(file.path, file.content, { encoding: 'utf8', flag: 'wx' });
    }
  }
  return skipped;
}
